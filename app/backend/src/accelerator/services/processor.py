from __future__ import annotations

import hashlib
from dataclasses import asdict, dataclass
from datetime import UTC, datetime
from typing import Protocol
from uuid import uuid4

from accelerator.config import Settings


@dataclass
class Job:
    id: str
    file_name: str
    status: str
    created_at: str
    summary: str = ""
    extracted_text: str = ""
    error: str = ""

    def to_dict(self) -> dict[str, str]:
        return asdict(self)


class DocumentProcessor(Protocol):
    async def upload(self, file_name: str, content: bytes) -> Job: ...

    async def process(self, job_id: str, blob_name: str) -> Job: ...

    async def get_job(self, job_id: str) -> Job | None: ...


class MockDocumentProcessor:
    def __init__(self) -> None:
        self._jobs: dict[str, Job] = {}

    async def upload(self, file_name: str, content: bytes) -> Job:
        job_id = str(uuid4())
        job = Job(
            id=job_id,
            file_name=file_name,
            status="queued",
            created_at=datetime.now(UTC).isoformat(),
        )
        self._jobs[job_id] = job
        return job

    async def process(self, job_id: str, blob_name: str) -> Job:
        job = self._jobs.get(job_id) or Job(
            id=job_id,
            file_name=blob_name,
            status="processing",
            created_at=datetime.now(UTC).isoformat(),
        )
        job.status = "completed"
        job.extracted_text = f"Mock extracted content for {blob_name}."
        job.summary = "Mock AI summary generated by the accelerator."
        self._jobs[job_id] = job
        return job

    async def get_job(self, job_id: str) -> Job | None:
        return self._jobs.get(job_id)


class AzureDocumentProcessor:
    def __init__(self, settings: Settings) -> None:
        from azure.ai.documentintelligence.aio import DocumentIntelligenceClient
        from azure.cosmos.aio import CosmosClient
        from azure.identity.aio import DefaultAzureCredential
        from azure.search.documents.aio import SearchClient
        from azure.storage.blob.aio import BlobServiceClient
        from openai import AsyncAzureOpenAI

        self._settings = settings
        self._credential = DefaultAzureCredential()
        self._blob = BlobServiceClient(settings.storage_endpoint, self._credential)
        self._cosmos = CosmosClient(settings.cosmos_endpoint, credential=self._credential)
        self._document_intelligence = DocumentIntelligenceClient(
            settings.document_intelligence_endpoint, self._credential
        )
        self._search = SearchClient(
            settings.search_endpoint, settings.search_index, self._credential
        )
        self._openai = AsyncAzureOpenAI(
            azure_endpoint=settings.foundry_openai_endpoint,
            azure_ad_token_provider=self._get_openai_token,
            api_version="2025-04-01-preview",
        )

    async def _get_openai_token(self) -> str:
        token = await self._credential.get_token("https://cognitiveservices.azure.com/.default")
        return token.token

    async def _jobs_container(self):
        database = await self._cosmos.create_database_if_not_exists(
            self._settings.cosmos_database
        )
        return await database.create_container_if_not_exists(
            id=self._settings.cosmos_container,
            partition_key={"paths": ["/id"], "kind": "Hash"},
        )

    async def upload(self, file_name: str, content: bytes) -> Job:
        job_id = str(uuid4())
        blob_name = f"{job_id}/{file_name}"
        container = self._blob.get_container_client(self._settings.submissions_container)
        await container.create_container()
        await container.upload_blob(blob_name, content, overwrite=False)
        job = Job(
            id=job_id,
            file_name=blob_name,
            status="queued",
            created_at=datetime.now(UTC).isoformat(),
        )
        jobs = await self._jobs_container()
        await jobs.upsert_item(job.to_dict())
        return job

    async def process(self, job_id: str, blob_name: str) -> Job:
        jobs = await self._jobs_container()
        job = Job(
            id=job_id,
            file_name=blob_name,
            status="processing",
            created_at=datetime.now(UTC).isoformat(),
        )
        await jobs.upsert_item(job.to_dict())

        container = self._blob.get_container_client(self._settings.submissions_container)
        content = await (await container.download_blob(blob_name)).readall()
        poller = await self._document_intelligence.begin_analyze_document(
            "prebuilt-layout", body=content
        )
        analysis = await poller.result()
        extracted_text = "\n".join(
            paragraph.content for paragraph in (analysis.paragraphs or [])
        )
        response = await self._openai.responses.create(
            model=self._settings.model_deployment,
            input=[
                {
                    "role": "system",
                    "content": "Summarize the document clearly and identify its main purpose.",
                },
                {"role": "user", "content": extracted_text[:100_000]},
            ],
        )
        summary = response.output_text
        search_id = hashlib.sha256(job_id.encode()).hexdigest()
        await self._search.upload_documents(
            [
                {
                    "id": search_id,
                    "jobId": job_id,
                    "fileName": blob_name,
                    "content": extracted_text,
                    "summary": summary,
                }
            ]
        )

        job.status = "completed"
        job.extracted_text = extracted_text
        job.summary = summary
        await jobs.upsert_item(job.to_dict())
        return job

    async def get_job(self, job_id: str) -> Job | None:
        jobs = await self._jobs_container()
        try:
            item = await jobs.read_item(job_id, partition_key=job_id)
        except Exception as exc:
            if getattr(exc, "status_code", None) == 404:
                return None
            raise
        return Job(**item)


def create_processor(settings: Settings) -> DocumentProcessor:
    if settings.mock_services:
        return MockDocumentProcessor()
    return AzureDocumentProcessor(settings)

